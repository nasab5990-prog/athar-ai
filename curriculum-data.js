window.ATHAR_ACADEMIC_YEAR = {
  current: '2026/2027',
  next: '2027/2028',
  getLabel(startYear) {
    const year = Number(startYear);
    if (!Number.isInteger(year) || year < 2000) return '';
    return year + '/' + (year + 1);
  },
  getNext(startYear) {
    const year = Number(startYear);
    if (!Number.isInteger(year) || year < 2000) return '';
    return (year + 1) + '/' + (year + 2);
  }
};
