-- ATHAR PostgreSQL schema v1
-- Apply with: npm run db:migrate
CREATE TABLE IF NOT EXISTS schema_migrations (
  version TEXT PRIMARY KEY,
  applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('teacher','senior_teacher','principal','parent','student')),
  school_id TEXT NOT NULL,
  student_id TEXT,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS otp_codes (
  email TEXT PRIMARY KEY,
  code_hash TEXT NOT NULL,
  expires_at BIGINT NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT,
  event TEXT NOT NULL,
  details TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS records (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id TEXT NOT NULL,
  owner_id BIGINT NOT NULL REFERENCES users(id),
  kind TEXT NOT NULL,
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_records_school_kind ON records(school_id, kind, id DESC);
CREATE INDEX IF NOT EXISTS idx_records_owner ON records(owner_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_records_student_id ON records(school_id, (payload->>'student_id'));

CREATE TABLE IF NOT EXISTS account_students (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  student_id TEXT NOT NULL,
  school_id TEXT NOT NULL,
  PRIMARY KEY (user_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_account_students_student ON account_students(school_id, student_id);

CREATE TABLE IF NOT EXISTS teacher_students (
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  student_id TEXT NOT NULL,
  school_id TEXT NOT NULL,
  PRIMARY KEY (user_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_teacher_students_student ON teacher_students(school_id, student_id);
